test("shared company export/copy/restore retains original identities, source and all opaque records",async()=>{
  await verifyAccountsCompanyArchive(original,original.companyId,2025);
  const archive=buildPersistedCompanyArchive({company:{id:original.companyId},incomeYear:2025,setups:[],shareholders:[],
    ledgerEntries:[],documents:[],filingPreviews:[],filingSubmissions:[],accountsCompanyArchive:original});
  const copied=JSON.parse(JSON.stringify(archive));
  const raw=JSON.stringify(copied);
  const restored=await copyCompanyYearArchive(raw,{targetCompanyId:"isolated-copy-metadata",expectedArchiveSha256:sha(raw),verifyAccounts:owningVerifier});
  assert.deepEqual(restored.restored.annualAccountsCompanyArchive,original);
  assert.notEqual(restored.restored.annualAccountsCompanyArchive,copied.annualAccountsCompanyArchive);
  assert.equal(restored.manifest.counts.annualAccountsDeliveryDrafts,2);
  assert.equal(restored.manifest.counts.annualAccountsDeliveryEvents,original.eventCount);
  assert.equal(restored.manifest.counts.annualAccountsDeliveryOriginals,original.originalCount);
  assert.equal(restored.manifest.annualAccountsArchiveSha256,original.sha256);
  assert.equal(assertRestoreIntegrity(restored).failures.some(code=>code.startsWith("annual_accounts_")),false);
  copied.annualAccountsCompanyArchive.canonicalJson="changed after copy";
  assert.equal(restored.restored.annualAccountsCompanyArchive.canonicalJson,original.canonicalJson);
  const body=source(original);
  assert.ok(body.events.some(row=>JSON.parse(row.canonicalJson).record.original?.purpose==="pdf"));
  assert.ok(body.events.some(row=>JSON.parse(row.canonicalJson).record.original?.purpose==="signature"));
});

for (const defect of ["scope","year","hash","source","codec","missing-draft","missing-event","duplicate-event","order",
  "foreign-binding","foreign-actor","coverage","original-bytes","count","original-count","extra"]) {
  test(`Accounts archive client and shared restore refuse ${defect}`,async()=>{
    const value=structuredClone(original),body=source(value);
    if(defect==="scope")value.companyId="15000000-0000-4000-8000-000000000099";
    else if(defect==="year")value.incomeYear=2024;
    else if(defect==="hash")value.sha256="0".repeat(64);
    else if(defect==="source")body.sourceSha256="0".repeat(64);
    else if(defect==="codec")body.contractVersion="future";
    else if(defect==="missing-draft")body.drafts.pop();
    else if(defect==="missing-event")body.events.pop();
    else if(defect==="duplicate-event")body.events[1]=body.events[0];
    else if(defect==="order")body.events.reverse();
    else if(defect==="coverage")body.coverage.deliveryImmutableValid=false;
    else if(defect==="original-bytes")body.events[5].canonicalJson+=" ";
    else if(defect==="count")value.eventCount--;
    else if(defect==="original-count")value.originalCount--;
    else if(defect==="extra")value.privileged=true;
    else {
      const index=0;
      const event=body.events[index],root=JSON.parse(event.canonicalJson);
      if(defect==="foreign-binding")root.record.binding.company_id.value="15000000-0000-4000-8000-000000000099";
      else if(defect==="foreign-actor")root.record.binding.actor_id.kind="SYSTEM";
      event.canonicalJson=canonical(root);event.sha256=sha(event.canonicalJson);
      body.coverage.deliveryEventDigests[String(event.sequence)]=event.sha256;
    }
    if(!["scope","year","hash","count","original-count","extra"].includes(defect))rehash(value,body);
    await assert.rejects(client(value).annualAccountsGetCompanyYearArchive(original.companyId,2025),error=>error instanceof TalliApiError&&error.status===502);
    const restored=restoreCompanyYearArchive({company:{id:original.companyId},incomeYear:2025,annualAccountsCompanyArchive:value},{targetCompanyId:original.companyId});
    assert.ok(assertRestoreIntegrity(restored).failures.includes("annual_accounts_archive_mismatch"));
  });
}

